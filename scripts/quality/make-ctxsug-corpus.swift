// Deterministic pseudo-random numbers so sizes and pictures are reproducible.
var seed: UInt64 = 0x5EED_C7C5_0001
func rnd() -> Double {
    seed = seed &* 6364136223846793005 &+ 1442695040888963407
    return Double(seed >> 11) / Double(1 << 53)
}

func url(_ name: String) -> URL { out.appendingPathComponent(name) }

// MARK: Text layout

let a4 = CGRect(x: 0, y: 0, width: 595, height: 842)

func attributed(_ text: String, size: CGFloat = 11) -> NSAttributedString {
    let style = NSMutableParagraphStyle()
    style.lineSpacing = 2.5
    style.paragraphSpacing = 6
    return NSAttributedString(string: text, attributes: [
        .font: NSFont(name: "Helvetica", size: size) ?? NSFont.systemFont(ofSize: size),
        .foregroundColor: NSColor.black, .paragraphStyle: style,
    ])
}

/// Draws as much of `text` as fits into `rect`; returns the drawn character count.
@discardableResult
func draw(_ text: NSAttributedString, from start: Int = 0, in rect: CGRect, context: CGContext) -> Int {
    let setter = CTFramesetterCreateWithAttributedString(text)
    let frame = CTFramesetterCreateFrame(setter, CFRange(location: start, length: 0), CGPath(rect: rect, transform: nil), nil)
    CTFrameDraw(frame, context)
    return CTFrameGetVisibleStringRange(frame).length
}

/// A text PDF with a real text layer. Each element of `pages` starts a new page and flows onward if long.
func textPDF(_ pages: [String], to target: URL, size: CGFloat = 11) {
    var box = a4
    guard let context = CGContext(target as CFURL, mediaBox: &box, nil) else { fatalError("pdf") }
    for page in pages {
        let text = attributed(page, size: size)
        var start = 0
        repeat {
            context.beginPDFPage(nil)
            let drawn = draw(text, from: start, in: a4.insetBy(dx: 64, dy: 60), context: context)
            context.endPDFPage()
            start += max(drawn, 1)
        } while start < text.length
    }
    context.closePDF()
}

/// A page rendered as pixels (for scans and phone photos).
func pageImage(_ text: String, scale: CGFloat, size: CGFloat = 11) -> CGImage {
    let w = Int(a4.width * scale), h = Int(a4.height * scale)
    let context = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: 0,
                            space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
    context.setFillColor(CGColor(gray: 0.98, alpha: 1))
    context.fill(CGRect(x: 0, y: 0, width: w, height: h))
    context.scaleBy(x: scale, y: scale)
    draw(attributed(text, size: size), in: a4.insetBy(dx: 64, dy: 60), context: context)
    return context.makeImage()!
}

/// Grainy overlay tile; repeated with offsets so JPEG sizes stay realistic.
let noiseTile: CGImage = {
    let n = 384
    var bytes = [UInt8](repeating: 0, count: n * n * 4)
    for i in 0..<(n * n) {
        let v = UInt8(110 + Int(rnd() * 36))
        bytes[i * 4] = v; bytes[i * 4 + 1] = v; bytes[i * 4 + 2] = v; bytes[i * 4 + 3] = 255
    }
    let provider = CGDataProvider(data: Data(bytes) as CFData)!
    return CGImage(width: n, height: n, bitsPerComponent: 8, bitsPerPixel: 32, bytesPerRow: n * 4,
                   space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.noneSkipLast.rawValue),
                   provider: provider, decode: nil, shouldInterpolate: false, intent: .defaultIntent)!
}()

func grain(_ context: CGContext, width: Int, height: Int, alpha: CGFloat) {
    context.saveGState()
    context.setAlpha(alpha)
    context.setBlendMode(.overlay)
    var y = -Int(rnd() * 200)
    while y < height {
        var x = -Int(rnd() * 200)
        while x < width {
            context.draw(noiseTile, in: CGRect(x: x, y: y, width: noiseTile.width, height: noiseTile.height))
            x += noiseTile.width
        }
        y += noiseTile.height
    }
    context.restoreGState()
}

func write(_ image: CGImage, to target: URL, type: UTType, quality: Double = 0.85) {
    let destination = CGImageDestinationCreateWithURL(target as CFURL, type.identifier as CFString, 1, nil)!
    CGImageDestinationAddImage(destination, image, [kCGImageDestinationLossyCompressionQuality: quality] as CFDictionary)
    guard CGImageDestinationFinalize(destination) else { fatalError("image \(target.lastPathComponent)") }
}

func canvas(_ w: Int, _ h: Int) -> CGContext {
    CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: 0,
              space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
}

/// Scanned letter: rasterized page, slight skew and grain, embedded as an image PDF without a text layer.
func scanPDF(_ text: String, to target: URL) {
    let page = pageImage(text, scale: 150.0 / 72.0)
    let c = canvas(page.width, page.height)
    c.setFillColor(CGColor(gray: 0.95, alpha: 1)); c.fill(CGRect(x: 0, y: 0, width: page.width, height: page.height))
    c.translateBy(x: CGFloat(page.width) / 2, y: CGFloat(page.height) / 2)
    c.rotate(by: 0.006)
    c.draw(page, in: CGRect(x: -page.width / 2, y: -page.height / 2, width: page.width, height: page.height))
    c.rotate(by: -0.006)
    c.translateBy(x: -CGFloat(page.width) / 2, y: -CGFloat(page.height) / 2)
    grain(c, width: page.width, height: page.height, alpha: 0.18)
    let jpeg = url(".scan-tmp.jpg")
    write(c.makeImage()!, to: jpeg, type: .jpeg, quality: 0.7)
    let source = CGImageSourceCreateWithURL(jpeg as CFURL, nil)!
    let scanned = CGImageSourceCreateImageAtIndex(source, 0, nil)!
    var box = a4
    let pdf = CGContext(target as CFURL, mediaBox: &box, nil)!
    pdf.beginPDFPage(nil)
    pdf.draw(scanned, in: a4)
    pdf.endPDFPage()
    pdf.closePDF()
    try? fm.removeItem(at: jpeg)
}

/// Phone photo of a paper page on a wooden table, 12 MP.
func pagePhoto(_ text: String, to target: URL, tilt: CGFloat, quality: Double = 0.82) {
    let w = 3024, h = 4032
    let c = canvas(w, h)
    let wood = CGGradient(colorsSpace: CGColorSpaceCreateDeviceRGB(), colors: [
        CGColor(red: 0.55, green: 0.38, blue: 0.24, alpha: 1), CGColor(red: 0.42, green: 0.28, blue: 0.17, alpha: 1)] as CFArray, locations: nil)!
    c.drawLinearGradient(wood, start: .zero, end: CGPoint(x: w, y: h), options: [])
    for _ in 0..<60 {
        c.setStrokeColor(CGColor(red: 0.35, green: 0.22, blue: 0.13, alpha: 0.25))
        c.setLineWidth(CGFloat(4 + rnd() * 10))
        let y = CGFloat(rnd()) * CGFloat(h)
        c.move(to: CGPoint(x: 0, y: y)); c.addCurve(to: CGPoint(x: CGFloat(w), y: y + CGFloat(rnd() * 200 - 100)),
                                                     control1: CGPoint(x: CGFloat(w) / 3, y: y + 60), control2: CGPoint(x: CGFloat(w) * 2 / 3, y: y - 60))
        c.strokePath()
    }
    let page = pageImage(text, scale: 4.2)
    c.saveGState()
    c.translateBy(x: CGFloat(w) / 2, y: CGFloat(h) / 2)
    c.rotate(by: tilt)
    c.setShadow(offset: CGSize(width: 18, height: -18), blur: 40, color: CGColor(gray: 0, alpha: 0.5))
    c.draw(page, in: CGRect(x: -page.width / 2, y: -page.height / 2, width: page.width, height: page.height))
    c.restoreGState()
    grain(c, width: w, height: h, alpha: 0.22)
    write(c.makeImage()!, to: target, type: .jpeg, quality: quality)
}

/// Outdoor scene: sky, sea or lawn, sun; 12 MP with grain.
func scenePhoto(to target: URL, ground: CGColor, quality: Double, landscape: Bool = true) {
    let w = landscape ? 4032 : 3024, h = landscape ? 3024 : 4032
    let c = canvas(w, h)
    let sky = CGGradient(colorsSpace: CGColorSpaceCreateDeviceRGB(), colors: [
        CGColor(red: 0.35, green: 0.6, blue: 0.92, alpha: 1), CGColor(red: 0.85, green: 0.92, blue: 1, alpha: 1)] as CFArray, locations: nil)!
    c.drawLinearGradient(sky, start: CGPoint(x: 0, y: h), end: CGPoint(x: 0, y: h / 2), options: [])
    c.setFillColor(ground); c.fill(CGRect(x: 0, y: 0, width: w, height: h / 2))
    c.setFillColor(CGColor(red: 1, green: 0.93, blue: 0.6, alpha: 1))
    c.fillEllipse(in: CGRect(x: w * 2 / 3, y: h * 3 / 4, width: 360, height: 360))
    for _ in 0..<140 {
        c.setFillColor(CGColor(red: rnd(), green: 0.5 + rnd() * 0.4, blue: rnd() * 0.5, alpha: 0.5))
        let r = CGFloat(20 + rnd() * 120)
        c.fillEllipse(in: CGRect(x: CGFloat(rnd()) * CGFloat(w), y: CGFloat(rnd()) * CGFloat(h) / 2, width: r, height: r * 0.6))
    }
    grain(c, width: w, height: h, alpha: 0.35)
    write(c.makeImage()!, to: target, type: .jpeg, quality: quality)
}

/// macOS-like screenshot with a window and text, as PNG (Retina 2880 × 1800).
func screenshot(to target: URL, title: String, lines: [String], table: [[String]]? = nil) {
    let w = 2880, h = 1800
    let c = canvas(w, h)
    c.setFillColor(CGColor(red: 0.2, green: 0.3, blue: 0.45, alpha: 1)); c.fill(CGRect(x: 0, y: 0, width: w, height: h))
    let window = CGRect(x: 360, y: 220, width: 2160, height: 1360)
    c.setShadow(offset: CGSize(width: 0, height: -20), blur: 60, color: CGColor(gray: 0, alpha: 0.5))
    c.setFillColor(CGColor(gray: 0.97, alpha: 1)); c.fill(window)
    c.setShadow(offset: .zero, blur: 0, color: nil)
    c.setFillColor(CGColor(gray: 0.88, alpha: 1)); c.fill(CGRect(x: window.minX, y: window.maxY - 104, width: window.width, height: 104))
    for (i, color) in [CGColor(red: 1, green: 0.37, blue: 0.34, alpha: 1), CGColor(red: 1, green: 0.74, blue: 0.18, alpha: 1), CGColor(red: 0.16, green: 0.79, blue: 0.25, alpha: 1)].enumerated() {
        c.setFillColor(color); c.fillEllipse(in: CGRect(x: window.minX + 40 + CGFloat(i) * 52, y: window.maxY - 70, width: 36, height: 36))
    }
    draw(attributed(title, size: 30), in: CGRect(x: window.minX + 220, y: window.maxY - 90, width: 1600, height: 70), context: c)
    if let table {
        let colW: CGFloat = 480, rowH: CGFloat = 76
        for (r, row) in table.enumerated() {
            for (col, cell) in row.enumerated() {
                let cellRect = CGRect(x: window.minX + 80 + CGFloat(col) * colW, y: window.maxY - 220 - CGFloat(r + 1) * rowH, width: colW, height: rowH)
                c.setStrokeColor(CGColor(gray: 0.75, alpha: 1)); c.setLineWidth(2); c.stroke(cellRect)
                if r == 0 { c.setFillColor(CGColor(gray: 0.9, alpha: 1)); c.fill(cellRect.insetBy(dx: 1, dy: 1)) }
                draw(attributed(cell, size: 30), in: cellRect.insetBy(dx: 16, dy: 14), context: c)
            }
        }
    } else {
        let dialog = CGRect(x: window.midX - 620, y: window.midY - 300, width: 1240, height: 560)
        c.setFillColor(CGColor(gray: 1, alpha: 1)); c.fill(dialog)
        c.setStrokeColor(CGColor(gray: 0.7, alpha: 1)); c.setLineWidth(3); c.stroke(dialog)
        c.setFillColor(CGColor(red: 1, green: 0.74, blue: 0.18, alpha: 1))
        c.fillEllipse(in: CGRect(x: dialog.minX + 60, y: dialog.maxY - 200, width: 120, height: 120))
        draw(attributed(lines.joined(separator: "\n"), size: 34), in: CGRect(x: dialog.minX + 220, y: dialog.minY + 140, width: 960, height: 380), context: c)
        c.setFillColor(CGColor(red: 0.2, green: 0.47, blue: 0.96, alpha: 1))
        c.fill(CGRect(x: dialog.maxX - 300, y: dialog.minY + 40, width: 240, height: 72))
    }
    write(c.makeImage()!, to: target, type: .png)
}

// MARK: Office Open XML via /usr/bin/zip

func zip(_ parts: [String: String], to target: URL) {
    let temp = out.appendingPathComponent(".zip-\(UUID().uuidString)", isDirectory: true)
    for (path, content) in parts {
        let file = temp.appendingPathComponent(path)
        try! fm.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        try! Data(content.utf8).write(to: file)
    }
    let process = Process()
    process.executableURL = URL(fileURLWithPath: "/usr/bin/zip")
    process.currentDirectoryURL = temp
    // [Content_Types].xml first, as Office writes it.
    process.arguments = ["-X", "-q", "-r", target.path, "[Content_Types].xml"] + parts.keys.filter { $0 != "[Content_Types].xml" }.sorted()
    try! process.run(); process.waitUntilExit()
    guard process.terminationStatus == 0 else { fatalError("zip \(target.lastPathComponent)") }
    try? fm.removeItem(at: temp)
}

func xml(_ s: String) -> String {
    s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;").replacingOccurrences(of: ">", with: "&gt;")
}

