/// One sheet; cells are (reference, value, formula?). Strings go to sharedStrings.
func xlsx(_ cells: [(String, String, String?)], to target: URL) {
    var strings: [String] = []
    var rows: [Int: [String]] = [:]
    for (ref, value, formula) in cells {
        let row = Int(ref.drop(while: { $0.isLetter }))!
        let cell: String
        if let formula {
            cell = "<c r=\"\(ref)\"><f>\(xml(formula))</f><v>\(value)</v></c>"
        } else if Double(value) != nil {
            cell = "<c r=\"\(ref)\"><v>\(value)</v></c>"
        } else {
            if !strings.contains(value) { strings.append(value) }
            cell = "<c r=\"\(ref)\" t=\"s\"><v>\(strings.firstIndex(of: value)!)</v></c>"
        }
        rows[row, default: []].append(cell)
    }
    let sheetRows = rows.keys.sorted().map { "<row r=\"\($0)\">\(rows[$0]!.joined())</row>" }.joined()
    zip([
        "[Content_Types].xml": """
        <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
        <Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/><Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/></Types>
        """,
        "_rels/.rels": """
        <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
        <Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>
        """,
        "xl/workbook.xml": """
        <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
        <workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Nebenkosten" sheetId="1" r:id="rId1"/></sheets></workbook>
        """,
        "xl/_rels/workbook.xml.rels": """
        <?xml version="1.0" encoding="UTF-8" standalone="yes"?>
