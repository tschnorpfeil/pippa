        <sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="\(strings.count)" uniqueCount="\(strings.count)">\(strings.map { "<si><t>\(xml($0))</t></si>" }.joined())</sst>
        """,
    ], to: target)
}

// MARK: Mail

func qp(_ text: String, charset: String.Encoding) -> String {
    var out = "", line = ""
    for byte in text.data(using: charset)! {
        let piece: String
        if byte == 0x0A { out += line + "\n"; line = ""; continue }
        if (byte >= 33 && byte <= 126 && byte != 61) || byte == 32 { piece = String(UnicodeScalar(byte)) }
        else { piece = String(format: "=%02X", byte) }
        if line.count + piece.count > 75 { out += line + "=\n"; line = "" }
        line += piece
    }
    return out + line
}

func base64Lines(_ data: Data) -> String {
    let s = data.base64EncodedString()
    return stride(from: 0, to: s.count, by: 76).map { i -> String in
        let start = s.index(s.startIndex, offsetBy: i)
        return String(s[start..<(s.index(start, offsetBy: 76, limitedBy: s.endIndex) ?? s.endIndex)])
    }.joined(separator: "\r\n")
}

